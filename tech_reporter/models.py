"""Data models for the Multi-Agent Technical Reporting System."""

from __future__ import annotations
from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone
from typing import List, Dict, Any, Optional
import json


@dataclass
class ResearchSource:
    """Represents a citation or information source."""
    url: str
    title: str
    snippet: str = ""
    author_or_domain: str = ""
    timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class ResearchDimension:
    """Specific technical domain or angle to investigate."""
    id: str
    title: str
    description: str
    key_questions: List[str] = field(default_factory=list)
    search_queries: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class ResearchPlan:
    """Structured plan generated by the Planner Agent."""
    technology: str
    scope: str
    target_audience: str
    dimensions: List[ResearchDimension] = field(default_factory=list)
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> ResearchPlan:
        dims = [
            ResearchDimension(**d) if isinstance(d, dict) else d
            for d in data.get("dimensions", [])
        ]
        return cls(
            technology=data["technology"],
            scope=data.get("scope", "Deep Technical Evaluation"),
            target_audience=data.get("target_audience", "Software Engineers & Architects"),
            dimensions=dims,
            created_at=data.get("created_at", datetime.now(timezone.utc).isoformat())
        )


@dataclass
class TechnicalFinding:
    """Synthesized finding for a specific research dimension."""
    dimension_id: str
    dimension_title: str
    key_takeaways: List[str] = field(default_factory=list)
    technical_details: str = ""
    code_snippets: List[Dict[str, str]] = field(default_factory=list)  # [{"language": "rust", "code": "...", "caption": "..."}]
    tradeoffs_and_challenges: List[str] = field(default_factory=list)
    benchmarks_or_metrics: List[str] = field(default_factory=list)
    sources: List[ResearchSource] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class ResearchDossier:
    """Complete collection of research compiled by the Research Agent."""
    technology: str
    plan: ResearchPlan
    findings: List[TechnicalFinding] = field(default_factory=list)
    all_sources: List[ResearchSource] = field(default_factory=list)
    summary_notes: str = ""
    completed_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class ReviewFeedback:
    """Quality review feedback provided by the Reviewer Agent."""
    score: int  # 1 to 100
    is_approved: bool
    summary: str
    strengths: List[str] = field(default_factory=list)
    missing_aspects: List[str] = field(default_factory=list)
    actionable_recommendations: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class ReportSection:
    """A section of the technical report."""
    title: str
    content: str
    slug: str
    subsections: List[ReportSection] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class TechnicalReport:
    """The final structured technical report produced by the Writer Agent."""
    title: str
    technology: str
    executive_summary: str
    target_audience: str
    version: str = "1.0"
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).strftime("%B %d, %Y"))
    sections: List[ReportSection] = field(default_factory=list)
    comparative_analysis: List[Dict[str, Any]] = field(default_factory=list)
    code_examples: List[Dict[str, str]] = field(default_factory=list)
    references: List[ResearchSource] = field(default_factory=list)
    markdown_content: str = ""
    html_content: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), indent=indent)


@dataclass
class AgentEvent:
    """An event emitted during multi-agent execution for monitoring & streaming."""
    timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).strftime("%H:%M:%S.%f")[:-3])
    agent: str = "System"
    event_type: str = "info"  # info, think, search, critique, write, success, error
    message: str = ""
    details: Optional[Dict[str, Any]] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)
